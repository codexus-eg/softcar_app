  /// Resolve [key] for [context]'s current locale (Arabic vs English).
  static String t(BuildContext context, String key) {
    final ar = Localizations.localeOf(context).languageCode == 'ar';
    return (ar ? _ar : _en)[key] ?? _en[key] ?? key;
  }

  /// Whether [context]'s current locale is Arabic.
  static bool isArabic(BuildContext context) =>
      Localizations.localeOf(context).languageCode == 'ar';

  /// Resolve [key] directly from an explicit [isArabic] flag.
  static String tl(bool isArabic, String key) =>
      (isArabic ? _ar : _en)[key] ?? _en[key] ?? key;
